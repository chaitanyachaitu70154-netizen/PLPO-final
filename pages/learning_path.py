"""
Learning Path Page for Phase 2.
Dedicated visualization of the dynamic curricular pathway,
optimizer reasoning engine, real-time path recalculation change log,
and interactive simulation controls.
Built 100% with Streamlit-native components with zero raw HTML.
"""

import streamlit as st
from typing import List, Optional
from core.knowledge_state import KnowledgeState
from core.optimizer import DynamicLearningPathOptimizer, LearningPath, PathNodeStatus, PathChangeLog
from core.misconception import Misconception, MisconceptionStatus
from components.learning_path_view import render_connected_learning_path

def render_learning_path_page(
    knowledge_state: KnowledgeState,
    learning_path: LearningPath,
    misconceptions: List[Misconception],
    optimizer: DynamicLearningPathOptimizer
):
    """Render the dynamic learning path page using Streamlit-native components."""
    st.title("🗺️ Personalized Curricular Pathway")
    st.caption("Dynamic sequencing generated by evaluating prerequisite readiness, knowledge gaps, and cognitive bugs.")

    # Show Path Adaptation Change Log (Feature 9 & 10)
    change_log: Optional[PathChangeLog] = learning_path.change_log
    if change_log and change_log.summary_message:
        with st.container(border=True):
            st.success(f"⚡ **CURRICULAR PATH ADAPTATION (Version {learning_path.version}):** {change_log.summary_message}")
            c_cl1, c_cl2 = st.columns(2)
            with c_cl1:
                if change_log.nodes_completed:
                    st.caption("Newly Mastered Milestones:")
                    for nc in change_log.nodes_completed:
                        st.markdown(f"- ✅ **{nc}**")
            with c_cl2:
                if change_log.nodes_unlocked:
                    st.caption("Newly Unlocked Milestones:")
                    for nu in change_log.nodes_unlocked:
                        st.markdown(f"- 🔓 **{nu}**")

    # Path Optimization Insights (Streamlit-native container)
    with st.container(border=True):
        st.subheader("⚙️ Optimizer Sequencing Heuristic (DAG + Mastery + Misconceptions)")
        col1, col2, col3, col4 = st.columns(4)
        with col1:
            with st.container(border=True):
                st.markdown("**1. Prerequisite Audit**")
                loops_m = knowledge_state.get_topic("Loops")
                score_str = f"{loops_m.percentage:.0f}%" if loops_m else "68%"
                st.caption(f"Evaluates Loops at {score_str}. Sequences targeted review prior to dependent function logic.")
        with col2:
            with st.container(border=True):
                st.markdown("**2. Bottleneck Isolation**")
                func_m = knowledge_state.get_topic("Functions")
                fscore_str = f"{func_m.percentage:.0f}%" if func_m else "43%"
                st.caption(f"Functions mastery is at {fscore_str}. Isolates this primary curricular bottleneck.")
        with col3:
            with st.container(border=True):
                st.markdown("**3. Misconception Injection**")
                active_misc = [m for m in misconceptions if m.status != MisconceptionStatus.REMEDIATED]
                if active_misc:
                    st.caption(f"Active: '{active_misc[0].title}'. Injected as mandatory pre-practice milestone.")
                else:
                    st.caption("All cognitive misconceptions remediated! Path streamlined for direct practice.")
        with col4:
            with st.container(border=True):
                st.markdown("**4. Gated Advancement**")
                st.caption("Data Structures & OOP are locked until Functions & Loops reach >= 70% threshold.")

    # Render connected path
    render_connected_learning_path(learning_path, interactive=True)

    st.divider()

    # Dynamic Path Simulator Section (Demonstrates flexible architecture)
    st.markdown("### 🎛️ Dynamic Path Adaptation Simulator")
    st.caption(
        "Demonstrates that the PLPO curricular trajectory is **dynamically responsive** to live evidence, "
        "not statically hardcoded. Adjust student mastery levels below to witness real-time path reconfiguration."
    )

    with st.expander("🛠️ Open Simulator Controls", expanded=False):
        col_s1, col_s2 = st.columns(2)
        with col_s1:
            current_func = int(knowledge_state.get_topic("Functions").percentage) if knowledge_state.get_topic("Functions") else 43
            func_val = st.slider(
                "Simulated Functions Mastery (%)",
                min_value=10,
                max_value=100,
                value=current_func,
                step=5,
                key="sim_slider_functions"
            )
            current_loops = int(knowledge_state.get_topic("Loops").percentage) if knowledge_state.get_topic("Loops") else 68
            loops_val = st.slider(
                "Simulated Loops Mastery (%)",
                min_value=10,
                max_value=100,
                value=current_loops,
                step=5,
                key="sim_slider_loops"
            )

        with col_s2:
            st.markdown("**Misconception Simulation Toggles:**")
            active_misc = [m for m in misconceptions if m.id == "misc_param_vs_arg"]
            is_rem = active_misc[0].status == MisconceptionStatus.REMEDIATED if active_misc else False
            mark_rem = st.checkbox("Mark 'Parameter vs Argument' as REMEDIATED", value=is_rem, key="sim_chk_param")

        if st.button("Apply Simulation & Recalculate Path", type="primary", key="btn_apply_sim"):
            knowledge_state.set_topic_score("Functions", func_val, reason="Simulator Adjustment")
            knowledge_state.set_topic_score("Loops", loops_val, reason="Simulator Adjustment")
            if active_misc:
                if mark_rem:
                    active_misc[0].mark_remediated()
                else:
                    active_misc[0].status = MisconceptionStatus.DETECTED

            new_path = optimizer.generate_path(
                knowledge_state=knowledge_state,
                misconceptions=misconceptions,
                previous_path=learning_path
            )
            st.session_state["current_learning_path"] = new_path
            st.success("✅ Path re-optimized instantly based on updated knowledge state parameters!")
            st.rerun()
